package com.gla.package_assignment.q3;

import static java.lang.Math.*;

public class StaticDemo {

    public static void main(String[] args) {

        double number = 16;

        System.out.println("Square Root: " + sqrt(number));
        System.out.println("Power (2^3): " + pow(2, 3));
        System.out.println("Maximum (10,20): " + max(10, 20));
        System.out.println("Minimum (5,2): " + min(5, 2));
        System.out.println("Absolute (-15): " + abs(-15));
    }
}